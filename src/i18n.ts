export type Language = 'zh' | 'en'

/** App language: Chinese for every Chinese locale, English for everything else. */
export function detectLanguage(): Language {
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

/** Calls `onChange` whenever the system language changes; returns the unsubscribe function. */
export function followSystemLanguage(onChange: () => void): () => void {
  window.addEventListener('languagechange', onChange)
  return () => window.removeEventListener('languagechange', onChange)
}

export function localeOf(language: Language): string {
  return language === 'zh' ? 'zh-CN' : 'en'
}

