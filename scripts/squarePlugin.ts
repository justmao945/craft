import { mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'
import type { Plugin, ResolvedConfig } from 'vite'
import { projectBuildOptions, projectPlugin, splitBuildOutput } from '../src/compiler/project.ts'

/**
 * Bundles every Square work (square/<id>/workspace) with the same compile core the in-app
 * compiler uses. One build writes
 *   square/<id>/dist/app.{js,css}   dev only: what preview.html runs
 *   src/square/works/<id>.json      sources + compiled output, bundled into the app
 * and the list of works goes to src/square/works/bundles.ts, which src/square/catalog.ts imports.
 * Generated files are ignored by git; the dev server and `npm run build` recreate them.
 * A work that does not compile fails the production build; under the dev server it is reported
 * and keeps its previous bundle, so a half-edited work never takes the server down.
 */
const SQUARE_ROOT = fileURLToPath(new URL('../square', import.meta.url))
const BUNDLES_DIR = fileURLToPath(new URL('../src/square/works', import.meta.url))
const ENTRY = 'src/main.tsx'
let bundled: string[] = []

async function readWorkspace(directory: string, prefix = ''): Promise<Record<string, string>> {
  const files: Record<string, string> = {}
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = `${directory}/${entry.name}`
    if (entry.isDirectory()) Object.assign(files, await readWorkspace(path, `${prefix}${entry.name}/`))
    else if (entry.isFile()) files[`${prefix}${entry.name}`] = await readFile(path, 'utf8')
  }
  return files
}

/** Bundles one work directory: undefined while it has no entry file, rejects while it does not compile. */
async function bundleWork(work: string): Promise<string | undefined> {
  try {
    if (!(await stat(`${work}/workspace/${ENTRY}`)).isFile()) return
  } catch {
    return
  }
  const files = await readWorkspace(`${work}/workspace`)
  const output = await build({ ...projectBuildOptions, entryPoints: [ENTRY], plugins: [projectPlugin(files)] })
  const { js, css } = splitBuildOutput(output.outputFiles)
  const id = work.slice(work.lastIndexOf('/') + 1)
  await mkdir(`${work}/dist`, { recursive: true })
  await writeFile(`${work}/dist/app.js`, js)
  await writeFile(`${work}/dist/app.css`, css)
  await mkdir(BUNDLES_DIR, { recursive: true })
  await writeFile(`${BUNDLES_DIR}/${id}.json`, JSON.stringify({ files, js, css }))
  return id
}

async function writeLoaders(): Promise<void> {
  const loaders = bundled.map((id) => `  ${id}: () => import('./${id}.json'),`)
  await mkdir(BUNDLES_DIR, { recursive: true })
  await writeFile(`${BUNDLES_DIR}/bundles.ts`, `// Generated by scripts/squarePlugin.ts from square/<id>/workspace. Do not edit.\nexport const bundles = {\n${loaders.join('\n')}\n}\n`)
}

/** Bundles every work that has a src/main.tsx and rewrites the loader table. Returns their ids. */
export async function buildSquare(failFast: boolean): Promise<string[]> {
  const entries = await readdir(SQUARE_ROOT, { withFileTypes: true })
  bundled = (await Promise.all(entries.filter((entry) => entry.isDirectory()).map(async (entry) => {
    try {
      return await bundleWork(`${SQUARE_ROOT}/${entry.name}`)
    } catch (error) {
      if (failFast) throw error
      console.error(`[square] ${entry.name} does not compile; keeping its previous bundle.\n${error instanceof Error ? error.message : error}`)
      return bundled.includes(entry.name) ? entry.name : undefined
    }
  }))).filter((id): id is string => id !== undefined).sort()
  await writeLoaders()
  return bundled
}

export function squareBundler(): Plugin {
  let failFast = true
  return {
    name: 'craft-square-works',
    configResolved(config: ResolvedConfig) {
      failFast = config.command === 'build'
    },
    async buildStart() {
      await buildSquare(failFast)
    },
    async watchChange(file) {
      // A source change rebuilds its own work; the files this writes never match.
      if (!file.startsWith(`${SQUARE_ROOT}/`) || !file.includes('/workspace/')) return
      const work = file.slice(0, file.indexOf('/workspace/'))
      try {
        const id = await bundleWork(work)
        if (id && !bundled.includes(id)) {
          bundled = [...bundled, id].sort()
          await writeLoaders()
        }
      } catch (error) {
        console.error(`[square] ${work.slice(work.lastIndexOf('/') + 1)} does not compile.\n${error instanceof Error ? error.message : error}`)
      }
    },
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  buildSquare(true).then((ids) => console.log(`Square works: ${ids.join(', ') || 'none'}`))
}
